/**
 * The product owner's review page (habitcraft-ser3): every acceptance test,
 * verbatim. The title and the body are copied from tests/*.test.ts; the only
 * changes are dropping `await` and trailing semicolons. Anything the generator
 * could not show as written makes it throw, so nothing is silently left out or
 * reworded.
 *
 * Plain JS rather than TypeScript so CI's Node 20 runs it without a loader;
 * render.d.mts gives the typed callers its types.
 */

import ts from 'typescript';

export function parseTestFile(source, file) {
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const lineOf = (node) => sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;
  const fail = (node, why) => {
    const text = node.getText(sf).split('\n')[0];
    throw new Error(`${file}:${lineOf(node)}: ${why}: ${text}`);
  };

  const scenarios = [];
  for (const statement of sf.statements) {
    if (ts.isImportDeclaration(statement)) continue;
    const call = ts.isExpressionStatement(statement) ? statement.expression : undefined;
    if (!call || !ts.isCallExpression(call) || call.expression.getText(sf) !== 'test') {
      fail(statement, 'only test(...) can be shown verbatim');
    }
    const [title, fn, ...rest] = call.arguments;
    if (!title || !ts.isStringLiteralLike(title)) fail(statement, 'the title must be written out');
    const isFunction = fn && (ts.isArrowFunction(fn) || ts.isFunctionExpression(fn));
    if (!isFunction || !ts.isBlock(fn.body) || rest.length > 0) {
      fail(statement, 'the test must be a title and a function body');
    }
    const body = source.slice(fn.body.getStart(sf) + 1, fn.body.end - 1);
    scenarios.push({ title: title.text, line: lineOf(statement), steps: steps(body) });
  }

  return { file, description: description(source), scenarios };
}

/** The body, dedented, without `await` and trailing semicolons. */
function steps(body) {
  const lines = body.split('\n');
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines.at(-1).trim()) lines.pop();
  const indent = Math.min(
    ...lines.filter((l) => l.trim()).map((l) => l.length - l.trimStart().length)
  );
  return lines
    .map((l) =>
      l
        .slice(indent)
        .replace(/^(\s*)await /, '$1')
        .replace(/;\s*$/, '')
        .trimEnd()
    )
    .join('\n');
}

/** The file's leading doc comment, without its `*` gutter. */
function description(source) {
  const [first] = ts.getLeadingCommentRanges(source, 0) ?? [];
  if (!first || !source.startsWith('/**', first.pos)) return '';
  return source
    .slice(first.pos + 3, first.end - 2)
    .split('\n')
    .map((l) => l.replace(/^\s*\* ?/, '').trim())
    .filter(Boolean)
    .join(' ');
}

const escape = (s) =>
  s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');

/** Escaped code with its strings and comments marked, so the domain words stand out. */
function highlight(code) {
  const token = /('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`[^`]*`)|(\/\/[^\n]*)/g;
  let html = '';
  let at = 0;
  for (const match of code.matchAll(token)) {
    html += escape(code.slice(at, match.index));
    const cls = match[1] ? 's' : 'c';
    html += `<span class="${cls}">${escape(match[0])}</span>`;
    at = match.index + match[0].length;
  }
  return html + escape(code.slice(at));
}

const anchor = (file) => file.replace(/\.test\.ts$/, '');

export function renderPage(files) {
  const total = files.reduce((n, f) => n + f.scenarios.length, 0);
  const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

  const nav = files
    .map((f) => `<a href="#${anchor(f.file)}">${escape(f.file)} (${f.scenarios.length})</a>`)
    .join('\n    ');

  const sections = files
    .map((f) => {
      const items = f.scenarios
        .map(
          (s) => `
      <li class="scenario">
        <div class="head"><h3>${escape(s.title)}</h3><span class="loc">${escape(f.file)}:${s.line}</span></div>
        <pre><code>${highlight(s.steps)}</code></pre>
      </li>`
        )
        .join('');
      return `
  <section id="${anchor(f.file)}">
    <div class="file-head">
      <h2>${escape(f.file)}</h2>
      ${f.description ? `<p>${escape(f.description)}</p>` : ''}
    </div>
    <ol class="scenarios">${items}
    </ol>
  </section>`;
    })
    .join('\n');

  return `${HEAD}
<div class="wrap">
  <header>
    <h1>HabitCraft Acceptance Tests</h1>
    <p class="lede">${plural(total, 'scenario')} in ${plural(files.length, 'file')}, copied from <code>acceptance/tests/</code>. Each is the test exactly as written: its title, then its steps, with only <code>await</code> and semicolons removed.</p>
    <p class="meta">Generated by <code>npm run review</code> in <code>acceptance/</code>. Do not edit; CI fails if it differs from the tests.</p>
  </header>
  <nav aria-label="Files">
    ${nav}
  </nav>
${sections}
</div>
`;
}

