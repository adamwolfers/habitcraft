#!/usr/bin/env node
/**
 * Report npm advisories across every package, measured against a committed baseline.
 *
 * WHY A BASELINE RATHER THAN A PASS/FAIL THRESHOLD. `npm audit` counts are not a
 * useful signal on their own. mobile/ reports 44 advisories on its "production"
 * surface, but npm marks `expo` as a production dependency, which drags the whole
 * Expo/Metro/Babel build toolchain in -- almost none of it reaches a device. A
 * count gate would either be permanently red there or tuned so loosely it says
 * nothing. Comparing against a recorded baseline asks the question that matters:
 * what appeared since somebody last looked?
 *
 * WHY NOT AN ALLOWLIST OF ACCEPTED ADVISORIES. Same reason. Mobile alone would
 * need 44 hand-written entries on day one, and the allowlist becomes the artifact
 * that rots. The baseline is generated, so refreshing it is one command.
 *
 * Usage:
 *   node scripts/audit-advisories.js            # report new/resolved vs baseline
 *   node scripts/audit-advisories.js --update   # rewrite the baseline from today
 *   node scripts/audit-advisories.js --json     # machine-readable result
 *
 * Exit codes: 0 when nothing new, 1 when new advisories appeared, 2 on error.
 * A caller that only wants the report passes --report-only to force 0.
 */
'use strict';

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BASELINE = path.join(__dirname, 'audit-baseline.json');

// Each package is audited on its production surface (--omit=dev). Dev-only
// advisories are reachable solely by someone already running this repo's code on
// their own machine, which is a different risk from what a user's browser or
// phone touches. `notes` explains any package whose count needs reading with care.
const PACKAGES = [
  { name: 'root', dir: '.', notes: 'build tooling only' },
  { name: 'backend', dir: 'backend', notes: 'internet-facing API' },
  { name: 'frontend', dir: 'frontend', notes: 'standalone Next server' },
  {
    name: 'mobile',
    dir: 'mobile',
    notes: "npm marks expo as a prod dep, so most of this is build toolchain, not shipped code",
  },
];

function audit(dir) {
  let stdout;
  try {
    stdout = execFileSync('npm', ['audit', '--json', '--omit=dev'], {
      cwd: path.join(ROOT, dir),
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      // npm audit exits non-zero whenever it finds anything, which is the normal
      // case here. The output is still valid JSON, so the status is ignored and
      // a genuine failure is caught by the parse below instead.
      stdio: ['ignore', 'pipe', 'ignore'],
    });
  } catch (err) {
    stdout = err.stdout;
  }

  if (!stdout) throw new Error(`npm audit produced no output in ${dir}`);
  return JSON.parse(stdout);
}

/**
 * Collect one entry per distinct advisory. npm nests `via` chains: an object is
 * a real advisory, a string is another package name that carries it transitively.
 * Only the objects are advisories, and the same one appears under every package
 * it reaches, so they are deduplicated by npm's numeric source id.
 */
function advisoriesFrom(report) {
  const found = new Map();

  for (const vuln of Object.values(report.vulnerabilities || {})) {
    for (const via of vuln.via || []) {
      if (typeof via !== 'object' || via.source == null) continue;
      found.set(String(via.source), {
        id: String(via.source),
        package: via.name,
        severity: via.severity,
        title: via.title,
        url: via.url,
        range: via.range,
      });
    }
  }

  return [...found.values()].sort((a, b) => a.id.localeCompare(b.id));
}

function collect() {
  const result = {};

  for (const pkg of PACKAGES) {
    const report = audit(pkg.dir);
    result[pkg.name] = {
      notes: pkg.notes,
      advisories: advisoriesFrom(report),
    };
  }

  return result;
}

const SEVERITY_ORDER = ['critical', 'high', 'moderate', 'low', 'info'];

function bySeverity(advisories) {
  const counts = {};
  for (const a of advisories) counts[a.severity] = (counts[a.severity] || 0) + 1;
  return SEVERITY_ORDER.filter((s) => counts[s])
    .map((s) => `${counts[s]} ${s}`)
    .join(', ');
}

function main() {
  const args = process.argv.slice(2);
  const update = args.includes('--update');
  const asJson = args.includes('--json');
  const reportOnly = args.includes('--report-only');

  const current = collect();

  if (update) {
    const payload = {
      generated: new Date().toISOString().slice(0, 10),
      note: 'Generated by scripts/audit-advisories.js --update. Do not hand-edit.',
      packages: current,
    };
    fs.writeFileSync(BASELINE, `${JSON.stringify(payload, null, 2)}\n`);
    const total = Object.values(current).reduce((n, p) => n + p.advisories.length, 0);
    console.log(`Baseline rewritten: ${total} advisories across ${PACKAGES.length} packages.`);
    return 0;
  }

  if (!fs.existsSync(BASELINE)) {
    console.error(`No baseline at ${path.relative(ROOT, BASELINE)}. Run with --update first.`);
    return 2;
  }

  const baseline = JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
  const added = [];
  const resolved = [];

  for (const pkg of PACKAGES) {
    const before = new Map(
      ((baseline.packages[pkg.name] || {}).advisories || []).map((a) => [a.id, a])
    );
    const after = new Map(current[pkg.name].advisories.map((a) => [a.id, a]));

    for (const [id, a] of after) if (!before.has(id)) added.push({ ...a, in: pkg.name });
    for (const [id, a] of before) if (!after.has(id)) resolved.push({ ...a, in: pkg.name });
  }

  if (asJson) {
    console.log(JSON.stringify({ baseline: baseline.generated, added, resolved }, null, 2));
    return added.length && !reportOnly ? 1 : 0;
  }

  console.log(`npm advisories, production surface only, against baseline ${baseline.generated}\n`);

  for (const pkg of PACKAGES) {
    const list = current[pkg.name].advisories;
    const summary = list.length ? bySeverity(list) : 'none';
    console.log(`  ${pkg.name.padEnd(9)} ${String(list.length).padStart(3)}  ${summary}`);
  }

  if (resolved.length) {
    console.log(`\nResolved since the baseline (${resolved.length}):`);
    for (const a of resolved) console.log(`  [${a.in}] ${a.severity} ${a.package} - ${a.title}`);
    console.log('\nRefresh with: node scripts/audit-advisories.js --update');
  }

  if (!added.length) {
    console.log('\nNo new advisories.');
    return 0;
  }

  console.log(`\nNEW since the baseline (${added.length}):`);
  for (const a of added) {
    console.log(`  [${a.in}] ${a.severity} ${a.package} ${a.range}`);
    console.log(`      ${a.title}`);
    console.log(`      ${a.url}`);
  }

  return reportOnly ? 0 : 1;
}

try {
  process.exit(main());
} catch (err) {
  console.error(`audit-advisories failed: ${err.message}`);
  process.exit(2);
}
